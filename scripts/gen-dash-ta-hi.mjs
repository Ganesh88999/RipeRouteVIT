// Sanity: no key left as pure English sentence for long strings (heuristic skip brands)
function looksEnglish(s) {
  if (!s || s.length < 12) return false
  if (/[அ-ஹऀ-ॿ]/.test(s)) return false
  // allow short tokens / filters / brands
  if (/^(24H|7D|30D|AI|KG|kWh|\/ KG|ETA|CO₂e)$/i.test(s)) return false
  return /^[\x20-\x7E]+$/.test(s) && /[a-zA-Z]{4,}/.test(s)
}
