function mergeLang(partial, full, label) {
  const out = {}
  const missing = []
  for (const key of Object.keys(en)) {
    if (partial[key] != null && String(partial[key]).trim() !== "") {
      out[key] = partial[key]
    } else if (full[key] != null) {
      out[key] = full[key]
    } else {
      missing.push(key)
      out[key] = en[key]
    }
  }
  if (missing.length) {
    console.error(`${label} missing translations:`, missing.join(", "))
    process.exitCode = 1
  }
  // Prefer full for keys where partial used English-y KG transliteration inconsistently —
  // but user said prefer existing partial when available. Keep partial.
  return out
}

